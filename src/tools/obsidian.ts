import https from "node:https";
import axios, { AxiosRequestConfig } from "axios";
import { ToolDefinition, formatToolResult } from "../types.js";

/**
 * Default Obsidian Local REST API endpoints per target.
 * - lera : OBSIDIAN_BASE_URL (default: http://obsidian:27124)
 * - lena : OBSIDIAN_LENA_BASE_URL (default: http://obsidian-lena:27124)
 */
const DEFAULT_LERA_BASE_URL = "http://obsidian:27124";
const DEFAULT_LENA_BASE_URL = "http://obsidian-lena:27124";

/**
 * Supported Obsidian vault targets.
 * - 'lera' uses OBSIDIAN_BASE_URL + OBSIDIAN_API_KEY
 * - 'lena' uses OBSIDIAN_LENA_BASE_URL + OBSIDIAN_LENA_API_KEY
 */
export type ObsidianTarget = "lera" | "lena";

/**
 * Shared HTTPS agent that permits self-signed certificates generated by
 * the Obsidian Local REST API plugin when HTTPS mode is used.
 */
const insecureHttpsAgent = new https.Agent({
  rejectUnauthorized: false,
});

/**
 * Resolves the target vault configuration (base URL and API key)
 * based on the provided target input.
 *
 * - 'lera' (default): reads OBSIDIAN_BASE_URL and OBSIDIAN_API_KEY
 * - 'lena': reads OBSIDIAN_LENA_BASE_URL and OBSIDIAN_LENA_API_KEY
 */
function resolveObsidianTarget(targetInput?: unknown): {
  target: ObsidianTarget;
  baseUrl: string;
  apiKey: string;
} {
  const raw = String(targetInput || "lera").trim().toLowerCase();

  if (raw === "lera" || raw === "" || raw === "default") {
    const baseUrl = (
      process.env.OBSIDIAN_BASE_URL || DEFAULT_LERA_BASE_URL
    )
      .trim()
      .replace(/\/+$/, "");

    const apiKey = (process.env.OBSIDIAN_API_KEY || "").trim();
    if (!apiKey) {
      throw new Error(
        "OBSIDIAN_API_KEY environment variable is not configured for target 'lera'. Please set OBSIDIAN_API_KEY in your .env file."
      );
    }

    return { target: "lera", baseUrl, apiKey };
  }

  if (raw === "lena") {
    const baseUrl = (
      process.env.OBSIDIAN_LENA_BASE_URL || DEFAULT_LENA_BASE_URL
    )
      .trim()
      .replace(/\/+$/, "");

    const apiKey = (process.env.OBSIDIAN_LENA_API_KEY || "").trim();
    if (!apiKey) {
      throw new Error(
        "OBSIDIAN_LENA_API_KEY environment variable is not configured for target 'lena'. Please set OBSIDIAN_LENA_API_KEY in your .env file."
      );
    }

    return { target: "lena", baseUrl, apiKey };
  }

  throw new Error(
    `Invalid Obsidian target '${raw}'. Supported values: 'lera' (default) or 'lena'.`
  );
}

/**
 * Normalizes and percent-encodes a vault-relative note path.
 * Automatically appends `.md` if the filename does not specify an extension.
 */
function normalizeVaultNotePath(
  rawPath: unknown,
  autoAppendMd = true
): { cleanPath: string; encodedPath: string } {
  const trimmed = String(rawPath ?? "")
    .trim()
    .replace(/\\/g, "/")
    .replace(/^\/+/, "")
    .replace(/\/+$/, "");

  if (!trimmed) {
    throw new Error("Parameter 'path' is required and cannot be empty.");
  }

  const segments = trimmed.split("/").filter(Boolean);
  if (segments.some((seg) => seg === "." || seg === "..")) {
    throw new Error(
      "Invalid vault path: relative traversal segments ('.' or '..') are not allowed."
    );
  }

  const lastIdx = segments.length - 1;
  if (autoAppendMd && !/\.[a-zA-Z0-9]+$/.test(segments[lastIdx])) {
    segments[lastIdx] = `${segments[lastIdx]}.md`;
  }

  const cleanPath = segments.join("/");
  const encodedPath = segments.map((seg) => encodeURIComponent(seg)).join("/");

  return { cleanPath, encodedPath };
}

/**
 * Normalizes and percent-encodes a vault-relative directory path.
 * Returns empty string for vault root (`""` or `"/"`).
 */
function normalizeVaultFolderPath(rawFolderPath: unknown): {
  cleanFolder: string;
  encodedFolder: string;
} {
  const trimmed = String(rawFolderPath ?? "")
    .trim()
    .replace(/\\/g, "/")
    .replace(/^\/+/, "")
    .replace(/\/+$/, "");

  if (!trimmed || trimmed === ".") {
    return { cleanFolder: "/", encodedFolder: "" };
  }

  const segments = trimmed.split("/").filter(Boolean);
  if (segments.some((seg) => seg === "." || seg === "..")) {
    throw new Error(
      "Invalid folder_path: relative traversal segments ('.' or '..') are not allowed."
    );
  }

  const cleanFolder = segments.join("/");
  const encodedFolder = segments.map((seg) => encodeURIComponent(seg)).join("/");

  return { cleanFolder, encodedFolder };
}

/**
 * Builds an Axios request configuration with Bearer authentication and
 * automatic self-signed TLS support if the baseUrl uses HTTPS.
 */
function createObsidianRequestConfig(
  baseUrl: string,
  apiKey: string,
  extraHeaders: Record<string, string> = {},
  timeoutMs = 15000
): AxiosRequestConfig {
  const isHttps = /^https:\/\//i.test(baseUrl);
  return {
    headers: {
      Authorization: `Bearer ${apiKey}`,
      ...extraHeaders,
    },
    timeout: timeoutMs,
    ...(isHttps ? { httpsAgent: insecureHttpsAgent } : {}),
  };
}

/**
 * Shared JSON Schema property definition for the `target` parameter
 * used across all Obsidian tools.
 */
const targetPropertySchema = {
  type: "string",
  enum: ["lera", "lena"],
  description:
    "Target Obsidian vault instance: 'lera' (default, uses OBSIDIAN_BASE_URL + OBSIDIAN_API_KEY) or 'lena' (uses OBSIDIAN_LENA_BASE_URL + OBSIDIAN_LENA_API_KEY). Defaults to 'lera'.",
  default: "lera",
};

/**
 * 1. Read Note from Obsidian Vault (`obsidian_read_note`)
 */
export const obsidianReadNoteTool: ToolDefinition = {
  name: "obsidian_read_note",
  description:
    "Read the content (and optional metadata/frontmatter/tags) of a note in the Obsidian vault via Obsidian Local REST API. Supports multi-target: 'lera' (default) or 'lena'.",
  inputSchema: {
    type: "object",
    properties: {
      path: {
        type: "string",
        description:
          "Vault-relative path to the note (e.g., 'Memory/profile.md' or 'Daily/2026-11-06.md'). If no file extension is provided, '.md' is appended automatically.",
      },
      include_metadata: {
        type: "boolean",
        description:
          "If true, returns parsed note JSON metadata including frontmatter, tags, links, backlinks, stat, and content. Default: false.",
        default: false,
      },
      target: targetPropertySchema,
    },
    required: ["path"],
  },
  handler: async (args) => {
    const { target, baseUrl, apiKey } = resolveObsidianTarget(args.target);
    const { cleanPath, encodedPath } = normalizeVaultNotePath(args.path);
    const includeMetadata = Boolean(args.include_metadata);

    const acceptHeader = includeMetadata
      ? "application/vnd.olrapi.note+json"
      : "text/markdown";

    const config = createObsidianRequestConfig(baseUrl, apiKey, {
      Accept: acceptHeader,
    });

    const response = await axios.get(`${baseUrl}/vault/${encodedPath}`, config);

    if (includeMetadata && typeof response.data === "object" && response.data !== null) {
      return formatToolResult({
        status: "ok",
        target,
        path: cleanPath,
        ...response.data,
      });
    }

    return formatToolResult({
      status: "ok",
      target,
      path: cleanPath,
      content:
        typeof response.data === "string"
          ? response.data
          : JSON.stringify(response.data, null, 2),
    });
  },
};

/**
 * 2. Append Content to Note in Obsidian Vault (`obsidian_append_note`)
 */
export const obsidianAppendNoteTool: ToolDefinition = {
  name: "obsidian_append_note",
  description:
    "Append Markdown content to the end of a note in the Obsidian vault via Obsidian Local REST API. Creates the note automatically if it does not exist yet. Supports multi-target: 'lera' (default) or 'lena'.",
  inputSchema: {
    type: "object",
    properties: {
      path: {
        type: "string",
        description:
          "Vault-relative path to the note (e.g., 'Memory/journal.md' or 'Daily/2026-11-06.md'). If no file extension is provided, '.md' is appended automatically.",
      },
      content: {
        type: "string",
        description: "Markdown text content to append to the note.",
      },
      target: targetPropertySchema,
    },
    required: ["path", "content"],
  },
  handler: async (args) => {
    const { target, baseUrl, apiKey } = resolveObsidianTarget(args.target);
    const { cleanPath, encodedPath } = normalizeVaultNotePath(args.path);

    if (args.content === undefined || args.content === null) {
      throw new Error("Parameter 'content' is required.");
    }
    const rawContent = String(args.content);
    const payload = rawContent.startsWith("\n") ? rawContent : `\n${rawContent}`;

    const config = createObsidianRequestConfig(baseUrl, apiKey, {
      "Content-Type": "text/markdown",
    });

    await axios.post(`${baseUrl}/vault/${encodedPath}`, payload, config);

    return formatToolResult({
      status: "ok",
      target,
      action: "append",
      path: cleanPath,
      appended_length: rawContent.length,
      message: `Successfully appended content to '${cleanPath}' on target '${target}'.`,
    });
  },
};

/**
 * 3. Write / Overwrite Note in Obsidian Vault (`obsidian_write_note`)
 */
export const obsidianWriteNoteTool: ToolDefinition = {
  name: "obsidian_write_note",
  description:
    "Create a new note or overwrite the full content of an existing note in the Obsidian vault via Obsidian Local REST API. Supports multi-target: 'lera' (default) or 'lena'.",
  inputSchema: {
    type: "object",
    properties: {
      path: {
        type: "string",
        description:
          "Vault-relative path to the note (e.g., 'Memory/summary.md' or 'Projects/plan.md'). If no file extension is provided, '.md' is appended automatically.",
      },
      content: {
        type: "string",
        description: "Full Markdown content to write into the note.",
      },
      target: targetPropertySchema,
    },
    required: ["path", "content"],
  },
  handler: async (args) => {
    const { target, baseUrl, apiKey } = resolveObsidianTarget(args.target);
    const { cleanPath, encodedPath } = normalizeVaultNotePath(args.path);

    if (args.content === undefined || args.content === null) {
      throw new Error("Parameter 'content' is required.");
    }
    const content = String(args.content);

    const config = createObsidianRequestConfig(baseUrl, apiKey, {
      "Content-Type": "text/markdown",
    });

    await axios.put(`${baseUrl}/vault/${encodedPath}`, content, config);

    return formatToolResult({
      status: "ok",
      target,
      action: "write",
      path: cleanPath,
      bytes_written: Buffer.byteLength(content, "utf8"),
      message: `Successfully wrote note '${cleanPath}' on target '${target}'.`,
    });
  },
};

/**
 * 4. Search Notes in Obsidian Vault (`obsidian_search_notes`)
 */
export const obsidianSearchNotesTool: ToolDefinition = {
  name: "obsidian_search_notes",
  description:
    "Search across all notes in the Obsidian vault for a text query via Obsidian Local REST API (`/search/simple/`). Returns matching filenames, relevance scores, and surrounding text context. Supports multi-target: 'lera' (default) or 'lena'.",
  inputSchema: {
    type: "object",
    properties: {
      query: {
        type: "string",
        description: "Search query text to find in the Obsidian vault.",
      },
      context_length: {
        type: "number",
        description:
          "Number of characters of surrounding context to include around each match. Default: 100.",
        default: 100,
      },
      target: targetPropertySchema,
    },
    required: ["query"],
  },
  handler: async (args) => {
    const { target, baseUrl, apiKey } = resolveObsidianTarget(args.target);
    const query = String(args.query || "").trim();
    if (!query) {
      throw new Error("Parameter 'query' is required and cannot be empty.");
    }

    const contextLength =
      args.context_length !== undefined ? Number(args.context_length) : 100;

    const config = createObsidianRequestConfig(baseUrl, apiKey, {
      Accept: "application/json",
    });
    config.params = {
      query,
      contextLength,
    };

    try {
      const response = await axios.post(
        `${baseUrl}/search/simple/`,
        null,
        config
      );
      const results = Array.isArray(response.data) ? response.data : [];

      return formatToolResult({
        status: "ok",
        target,
        query,
        total_files_matched: results.length,
        results,
      });
    } catch (error: any) {
      if (error?.response?.status === 404) {
        return formatToolResult({
          status: "ok",
          target,
          query,
          total_files_matched: 0,
          results: [],
        });
      }
      throw error;
    }
  },
};

/**
 * 5. List Files and Folders in Obsidian Vault (`obsidian_list_files`)
 */
export const obsidianListFilesTool: ToolDefinition = {
  name: "obsidian_list_files",
  description:
    "List files and subdirectories inside a specific folder (or root directory) of the Obsidian vault via Obsidian Local REST API. Supports multi-target: 'lera' (default) or 'lena'.",
  inputSchema: {
    type: "object",
    properties: {
      folder_path: {
        type: "string",
        description:
          "Vault-relative folder path to list (e.g., 'Memory' or 'Projects/2026'). Leave empty ('') or '/' to list the vault root directory.",
        default: "",
      },
      target: targetPropertySchema,
    },
    required: [],
  },
  handler: async (args) => {
    const { target, baseUrl, apiKey } = resolveObsidianTarget(args.target);
    const rawFolder = args.folder_path ?? args.path ?? "";
    const { cleanFolder, encodedFolder } = normalizeVaultFolderPath(rawFolder);

    const endpoint = encodedFolder
      ? `${baseUrl}/vault/${encodedFolder}/`
      : `${baseUrl}/vault/`;

    const config = createObsidianRequestConfig(baseUrl, apiKey, {
      Accept: "application/json",
    });

    const response = await axios.get(endpoint, config);
    const files: string[] = Array.isArray(response.data?.files)
      ? response.data.files
      : [];

    return formatToolResult({
      status: "ok",
      target,
      folder_path: cleanFolder,
      total_entries: files.length,
      files,
    });
  },
};

export default [
  obsidianReadNoteTool,
  obsidianAppendNoteTool,
  obsidianWriteNoteTool,
  obsidianSearchNotesTool,
  obsidianListFilesTool,
];
